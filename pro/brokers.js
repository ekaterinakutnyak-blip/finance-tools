/* Профиль по тексту файла. Сначала те, у кого совпали и подпись, и колонки —
   это надёжнее, чем одно упоминание названия: «Сбербанк» встречается и как
   название бумаги в чужом отчёте. */
function detectBroker(txt){
  const t=String(txt||'');
  const strong=BROKERS.filter(b=>b.sign.test(t) && b.cols && b.cols.test(t));
  if(strong.length===1) return strong[0];
  const weak=BROKERS.filter(b=>b.sign.test(t));
  return weak.length===1?weak[0]:null;
}

function brokerById(id){ return BROKERS.filter(b=>b.id===id)[0]||null; }

/* Регулярка колонки из профиля, если она там есть.
   Сам поиск остаётся на странице: там же знают про группы колонок
   «начало / конец периода», а без этого правило хватает первое попавшееся
   совпадение и берёт начало периода вместо конца. */
function ruleRe(rules, part, slot){
  if(!rules || !rules[part]) return null;
  return rules[part][slot] || null;
}

/* Выбранный в списке брокер — он главнее найденного: человек знает, что
   загружает. Возвращаем и то и другое, чтобы сказать о расхождении. */
function brokerFor(txt){
  const picked=brokerById((document.getElementById('brokerSel')||{}).value||'');
  const found=detectBroker(txt);
  return {use:picked||found, picked:picked, found:found,
          mismatch:!!(picked && found && picked.id!==found.id),
          broken:!!(picked && picked.expect && !picked.expect.test(String(txt||'')))};
}

/* Заполняет список брокеров на странице, если он там есть. */
function fillBrokerSelect(id){
  const sel=document.getElementById(id||'brokerSel');
  if(!sel || sel.dataset.filled) return;
  BROKERS.forEach(b=>{
    const o=document.createElement('option'); o.value=b.id; o.textContent='Брокер: '+b.label;
    sel.appendChild(o);
  });
  sel.dataset.filled='1';
}

/* Строка про брокера для сообщения после загрузки отчёта. */
function brokerNote(b){
  if(!b) return ' Брокер не опознан, читаю общими правилами.';
  if(b.mismatch) return ' <b>Вы выбрали '+b.picked.label+', а по содержимому это похоже на '+b.found.label+
                        '</b> — читаю так, как выбрали вы. Если ошиблись, поменяйте в списке и загрузите снова.';
  if(b.broken)   return ' <b>В файле нет того, что бывает в отчёте '+b.picked.label+'</b> — возможно, выбран не тот брокер.';
  if(b.use)      return ' Брокер: <b>'+b.use.label+'</b>.';
  return ' Брокер не опознан, читаю общими правилами.';
}
